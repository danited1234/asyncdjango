"""Exercise the initial model API against a disposable PostgreSQL database."""

import importlib.util
import os
import unittest


HAS_DATABASE = bool(os.environ.get("ASYNCDJANGO_DATABASE_URL"))
HAS_DRIVER = importlib.util.find_spec("asyncpg") is not None


@unittest.skipUnless(HAS_DATABASE and HAS_DRIVER, "PostgreSQL URL and asyncpg required")
class ModelIntegrationTests(unittest.IsolatedAsyncioTestCase):
    async def asyncSetUp(self) -> None:
        from asyncdjango.db import AsyncPostgres, models

        class User(models.Model):
            email = models.CharField(max_length=255)
            age = models.IntegerField(null=True)
            active = models.BooleanField(default=True)

            class Meta:
                db_table = "asyncdjango_test_users"

        self.User = User
        self.database = AsyncPostgres(os.environ["ASYNCDJANGO_DATABASE_URL"])
        await self.database.connect()
        await self.database.execute(
            'CREATE TABLE "asyncdjango_test_users" ('
            '"id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, '
            '"email" VARCHAR(255) NOT NULL, '
            '"age" INTEGER NULL, '
            '"active" BOOLEAN NOT NULL)'
        )

    async def asyncTearDown(self) -> None:
        await self.database.execute('DROP TABLE "asyncdjango_test_users"')
        await self.database.close()

    async def test_native_model_crud(self) -> None:
        users = self.User.objects.using(self.database)
        created = await users.create(email="a@example.com", age=24)
        self.assertIsInstance(created.id, int)
        self.assertTrue(created.active)

        found = await users.filter(age__gte=18).get(email="a@example.com")
        self.assertEqual(found.pk, created.pk)
        self.assertEqual(await users.count(), 1)
        self.assertTrue(await users.filter(active=True).exists())
        self.assertEqual(len(await users.fetch_all()), 1)
        self.assertEqual(
            [user.email async for user in users.order_by("id")],
            ["a@example.com"],
        )

        found.age = 25
        await found.save()
        self.assertEqual((await users.get(pk=created.pk)).age, 25)
        self.assertEqual(await users.filter(pk=created.pk).update(active=False), 1)
        self.assertFalse(await users.filter(active=True).exists())
        self.assertEqual(await users.filter(pk=created.pk).delete(), 1)
        self.assertEqual(await users.count(), 0)

    async def test_transaction_rollback_only_and_nested_savepoint(self) -> None:
        users = self.User.objects
        async with self.database.transaction() as transaction:
            await users.using(transaction).create(email="rolled@example.com")
            transaction.set_rollback()
        self.assertEqual(await users.using(self.database).count(), 0)

        async with self.database.transaction() as transaction:
            async with transaction.transaction():
                await users.using(transaction).create(email="nested@example.com")
                transaction.set_rollback()
            await users.using(transaction).create(email="kept@example.com")
        saved = await users.using(self.database).fetch_all()
        self.assertEqual([user.email for user in saved], ["kept@example.com"])

    async def test_atomic_and_select_for_update(self) -> None:
        from asyncdjango.db import transaction, using_database

        with using_database(self.database):
            created = await self.User.objects.create(email="locked@example.com")
            with self.assertRaisesRegex(RuntimeError, "requires transaction"):
                await self.User.objects.select_for_update().get(pk=created.pk)
            async with transaction.atomic():
                user = await self.User.objects.select_for_update().get(pk=created.pk)
                user.age = 30
                await user.save()
                async with transaction.atomic() as nested:
                    await self.User.objects.filter(pk=created.pk).update(age=31)
                    nested.set_rollback()
                self.assertEqual((await self.User.objects.get(pk=created.pk)).age, 30)
            self.assertEqual((await self.User.objects.get(pk=created.pk)).age, 30)

    async def test_foreign_key_and_select_related(self) -> None:
        from asyncdjango.db import models
        from asyncdjango.db.migrations import apply_migration, initial_migration

        class Organization(models.Model):
            name = models.CharField(max_length=50)

            class Meta:
                db_table = "asyncdjango_test_organizations"

        class Employee(models.Model):
            organization = models.ForeignKey(Organization, on_delete=models.CASCADE)
            name = models.CharField(max_length=50)

            class Meta:
                db_table = "asyncdjango_test_employees"

        migration = initial_migration("test_0003_relationships", [Employee, Organization])
        await apply_migration(self.database, migration)
        try:
            from asyncdjango.db import using_database
            from asyncdjango.serializers import ModelSerializer

            class EmployeeSerializer(ModelSerializer):
                class Meta:
                    model = Employee
                    fields = ("organization", "name")

            with using_database(self.database):
                invalid = EmployeeSerializer(data={
                    "organization": 999999, "name": "Missing org"
                })
                self.assertFalse(await invalid.ais_valid())
                self.assertIn("organization", invalid.errors)
            organization = await Organization.objects.using(self.database).create(
                name="Acme"
            )
            employee = await Employee.objects.using(self.database).create(
                organization=organization, name="Alex"
            )
            plain = await Employee.objects.using(self.database).get(pk=employee.pk)
            self.assertEqual(plain.organization_id, organization.pk)
            with self.assertRaises(models.UnloadedRelationError):
                _ = plain.organization
            selected = await (Employee.objects.using(self.database)
                              .select_related("organization")
                              .get(organization_id=organization.pk))
            self.assertEqual(selected.organization.name, "Acme")
            self.assertEqual(selected.organization.pk, organization.pk)
            await Organization.objects.using(self.database).filter(
                pk=organization.pk
            ).delete()
            self.assertEqual(await Employee.objects.using(self.database).count(), 0)
        finally:
            await self.database.execute('DROP TABLE IF EXISTS "asyncdjango_test_employees"')
            await self.database.execute('DROP TABLE IF EXISTS "asyncdjango_test_organizations"')
            await self.database.execute(
                'DELETE FROM "_asyncdjango_migrations" WHERE "name" = $1',
                migration.name,
            )
