"""Schema generation and application against disposable PostgreSQL."""

import importlib.util
import os
import unittest

from asyncdjango.db import models
from asyncdjango.db.migrations import initial_migration


class MigrationGenerationTests(unittest.TestCase):
    def test_sql_uses_supported_fields_and_quoted_identifiers(self) -> None:
        class Event(models.Model):
            title = models.CharField(max_length=40)
            published = models.BooleanField(default=False)
            occurred_at = models.DateTimeField(null=True)

            class Meta:
                db_table = 'odd"table'

        migration = initial_migration("0001_initial", [Event])
        self.assertEqual(migration.statements, (
            'CREATE TABLE "odd""table" ('
            '"id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, '
            '"title" VARCHAR(40) NOT NULL, '
            '"published" BOOLEAN NOT NULL, '
            '"occurred_at" TIMESTAMPTZ)',
        ))
        self.assertEqual(len(migration.checksum), 64)


HAS_DATABASE = bool(os.environ.get("ASYNCDJANGO_DATABASE_URL"))
HAS_DRIVER = importlib.util.find_spec("asyncpg") is not None


@unittest.skipUnless(HAS_DATABASE and HAS_DRIVER, "PostgreSQL URL and asyncpg required")
class MigrationIntegrationTests(unittest.IsolatedAsyncioTestCase):
    async def test_apply_once_and_detect_changed_sql(self) -> None:
        from asyncdjango.db import AsyncPostgres
        from asyncdjango.db.migrations import Migration, apply_migration

        class Item(models.Model):
            name = models.CharField(max_length=60)

            class Meta:
                db_table = "asyncdjango_migration_test_items"

        database = AsyncPostgres(os.environ["ASYNCDJANGO_DATABASE_URL"])
        await database.connect()
        try:
            migration = initial_migration("test_0001_items", [Item])
            self.assertTrue(await apply_migration(database, migration))
            self.assertFalse(await apply_migration(database, migration))
            with self.assertRaisesRegex(RuntimeError, "different SQL"):
                await apply_migration(database, Migration(
                    migration.name, ("SELECT 1",)
                ))
            item = await Item.objects.using(database).create(name="created")
            self.assertEqual(item.name, "created")
        finally:
            await database.execute('DROP TABLE IF EXISTS "asyncdjango_migration_test_items"')
            await database.execute(
                'DELETE FROM "_asyncdjango_migrations" WHERE "name" = $1',
                "test_0001_items",
            )
            await database.close()
