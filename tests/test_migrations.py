"""Schema generation and application against disposable PostgreSQL."""

import importlib.util
import os
import unittest

from asyncdjango.db import models
from asyncdjango.db.migrations import SQLExpression, alter_migration, initial_migration


class MigrationGenerationTests(unittest.TestCase):
    def test_sql_uses_supported_fields_and_quoted_identifiers(self) -> None:
        class Event(models.Model):
            title = models.CharField(max_length=40)
            published = models.BooleanField(default=False)
            occurred_at = models.DateTimeField(null=True)

            class Meta:
                db_table = 'odd"table'

        migration = initial_migration("0001_initial", [Event])
        self.assertEqual(migration.statements, (
            'CREATE TABLE "odd""table" ('
            '"id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, '
            '"title" VARCHAR(40) NOT NULL, '
            '"published" BOOLEAN NOT NULL, '
            '"occurred_at" TIMESTAMPTZ)',
        ))
        self.assertEqual(len(migration.checksum), 64)

    def test_alter_sql_requires_explicit_drop_opt_in(self) -> None:
        class Before(models.Model):
            title = models.CharField(max_length=20)
            obsolete = models.IntegerField(null=True)

            class Meta:
                db_table = "asyncdjango_alter_generation"

        class After(models.Model):
            title = models.CharField(max_length=40)
            note = models.CharField(max_length=15, null=True)

            class Meta:
                db_table = "asyncdjango_alter_generation"

        with self.assertRaisesRegex(ValueError, "allow_destructive"):
            alter_migration("test_0002_alter", [Before], [After])
        migration = alter_migration("test_0002_alter", [Before], [After],
                                    allow_destructive=True)
        self.assertEqual(migration.statements, (
            'ALTER TABLE "asyncdjango_alter_generation" ALTER COLUMN "title" '
            'TYPE VARCHAR(40) USING "title"::VARCHAR(40)',
            'ALTER TABLE "asyncdjango_alter_generation" ADD COLUMN "note" '
            'VARCHAR(15)',
            'ALTER TABLE "asyncdjango_alter_generation" DROP COLUMN "obsolete"',
        ))

    def test_sql_defaults_are_quoted_and_altered(self) -> None:
        class Before(models.Model):
            label = models.CharField(max_length=20, db_default="O'Reilly")
            created_at = models.DateTimeField(
                db_default=SQLExpression("CURRENT_TIMESTAMP")
            )

            class Meta:
                db_table = "asyncdjango_default_generation"

        class After(models.Model):
            label = models.CharField(max_length=20, db_default="Updated")
            created_at = models.DateTimeField(
                db_default=SQLExpression("CURRENT_TIMESTAMP")
            )

            class Meta:
                db_table = "asyncdjango_default_generation"

        self.assertIn("DEFAULT 'O''Reilly'", initial_migration(
            "test_default_1", [Before]
        ).statements[0])
        self.assertEqual(alter_migration("test_default_2", [Before], [After]).statements,
                         ('ALTER TABLE "asyncdjango_default_generation" '
                          'ALTER COLUMN "label" SET DEFAULT \'Updated\'',))
        with self.assertRaises(ValueError):
            SQLExpression("DROP TABLE users")


HAS_DATABASE = bool(os.environ.get("ASYNCDJANGO_DATABASE_URL"))
HAS_DRIVER = importlib.util.find_spec("asyncpg") is not None


@unittest.skipUnless(HAS_DATABASE and HAS_DRIVER, "PostgreSQL URL and asyncpg required")
class MigrationIntegrationTests(unittest.IsolatedAsyncioTestCase):
    async def test_apply_once_and_detect_changed_sql(self) -> None:
        from asyncdjango.db import AsyncPostgres
        from asyncdjango.db.migrations import Migration, apply_migration

        class Item(models.Model):
            name = models.CharField(max_length=60)

            class Meta:
                db_table = "asyncdjango_migration_test_items"

        database = AsyncPostgres(os.environ["ASYNCDJANGO_DATABASE_URL"])
        await database.connect()
        try:
            migration = initial_migration("test_0001_items", [Item])
            self.assertTrue(await apply_migration(database, migration))
            self.assertFalse(await apply_migration(database, migration))
            with self.assertRaisesRegex(RuntimeError, "different SQL"):
                await apply_migration(database, Migration(
                    migration.name, ("SELECT 1",)
                ))
            item = await Item.objects.using(database).create(name="created")
            self.assertEqual(item.name, "created")
        finally:
            await database.execute('DROP TABLE IF EXISTS "asyncdjango_migration_test_items"')
            await database.execute(
                'DELETE FROM "_asyncdjango_migrations" WHERE "name" = $1',
                "test_0001_items",
            )
            await database.close()

    async def test_alter_drop_preserves_data_and_failed_change_rolls_back(self) -> None:
        from asyncdjango.db import AsyncPostgres
        from asyncdjango.db.migrations import apply_migration

        class Before(models.Model):
            title = models.CharField(max_length=20)
            obsolete = models.IntegerField(null=True)

            class Meta:
                db_table = "asyncdjango_alter_live"

        class After(models.Model):
            title = models.CharField(max_length=40)
            note = models.CharField(max_length=15, null=True)

            class Meta:
                db_table = "asyncdjango_alter_live"

        class Required(models.Model):
            title = models.CharField(max_length=40)
            note = models.CharField(max_length=15)

            class Meta:
                db_table = "asyncdjango_alter_live"

        database = AsyncPostgres(os.environ["ASYNCDJANGO_DATABASE_URL"])
        await database.connect()
        try:
            first = initial_migration("test_0005_alter_initial", [Before])
            second = alter_migration("test_0006_alter_columns", [Before], [After],
                                     allow_destructive=True)
            third = alter_migration("test_0007_require_note", [After], [Required])
            await apply_migration(database, first)
            original = await Before.objects.using(database).create(
                title="Kept", obsolete=12
            )
            self.assertTrue(await apply_migration(database, second))
            self.assertFalse(await apply_migration(database, second))
            changed = await After.objects.using(database).get(pk=original.pk)
            self.assertEqual((changed.title, changed.note), ("Kept", None))
            with self.assertRaises(Exception):
                await apply_migration(database, third)
            rows = await database.fetch(
                'SELECT "name" FROM "_asyncdjango_migrations" WHERE "name" = $1',
                third.name,
            )
            self.assertEqual(rows, [])
            await After.objects.using(database).filter(pk=original.pk).update(
                note="filled"
            )
            self.assertTrue(await apply_migration(database, third))
            self.assertEqual((await Required.objects.using(database).get(
                pk=original.pk
            )).note, "filled")
        finally:
            await database.execute('DROP TABLE IF EXISTS "asyncdjango_alter_live"')
            for name in ("test_0005_alter_initial", "test_0006_alter_columns",
                         "test_0007_require_note"):
                await database.execute(
                    'DELETE FROM "_asyncdjango_migrations" WHERE "name" = $1', name
                )
            await database.close()

    async def test_database_defaults_apply_to_orm_inserts_and_alter(self) -> None:
        from asyncdjango.db import AsyncPostgres
        from asyncdjango.db.migrations import apply_migration
        from asyncdjango.db import using_database
        from asyncdjango.serializers import ModelSerializer

        class Before(models.Model):
            label = models.CharField(max_length=20, db_default="queued")
            created_at = models.DateTimeField(
                db_default=SQLExpression("CURRENT_TIMESTAMP")
            )

            class Meta:
                db_table = "asyncdjango_default_live"

        class After(models.Model):
            label = models.CharField(max_length=20, db_default="ready")
            created_at = models.DateTimeField(
                db_default=SQLExpression("CURRENT_TIMESTAMP")
            )

            class Meta:
                db_table = "asyncdjango_default_live"

        class BeforeSerializer(ModelSerializer):
            class Meta:
                model = Before
                fields = ("id", "label", "created_at")

        database = AsyncPostgres(os.environ["ASYNCDJANGO_DATABASE_URL"])
        await database.connect()
        try:
            first = initial_migration("test_0008_default_initial", [Before])
            second = alter_migration("test_0009_default_alter", [Before], [After])
            await apply_migration(database, first)
            original = await Before.objects.using(database).create()
            self.assertEqual(original.label, "queued")
            self.assertIsNotNone(original.created_at)
            other = Before().using(database)
            await other.save()
            self.assertEqual(other.label, "queued")
            with using_database(database):
                serializer = BeforeSerializer(data={})
                self.assertTrue(await serializer.ais_valid())
                self.assertEqual((await serializer.asave()).label, "queued")
            await apply_migration(database, second)
            updated = await After.objects.using(database).create()
            self.assertEqual(updated.label, "ready")
            self.assertEqual(await After.objects.using(database).count(), 4)
        finally:
            await database.execute('DROP TABLE IF EXISTS "asyncdjango_default_live"')
            for name in ("test_0008_default_initial", "test_0009_default_alter"):
                await database.execute(
                    'DELETE FROM "_asyncdjango_migrations" WHERE "name" = $1', name
                )
            await database.close()
