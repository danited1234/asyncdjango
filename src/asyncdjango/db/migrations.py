"""Initial PostgreSQL schema migrations for the supported field subset."""

from __future__ import annotations

from dataclasses import dataclass
from hashlib import sha256
from typing import Iterable

from .models import (
    AutoField, BooleanField, CharField, DateTimeField, Field, ForeignKey, IntegerField,
    Model, _quote,
)
from .postgres import AsyncPostgres


@dataclass(frozen=True)
class Migration:
    name: str
    statements: tuple[str, ...]

    @property
    def checksum(self) -> str:
        return sha256("\n".join(self.statements).encode("utf-8")).hexdigest()


def _column_sql(field: Field) -> str:
    if isinstance(field, ForeignKey):
        target = field.to
        target_pk = target._meta.fields[target._meta.pk_name]
        if isinstance(target_pk, (AutoField, IntegerField)):
            type_sql = "BIGINT" if isinstance(target_pk, AutoField) else "INTEGER"
        elif isinstance(target_pk, CharField):
            type_sql = f"VARCHAR({target_pk.max_length})"
        else:
            raise TypeError("Unsupported foreign key target")
    elif isinstance(field, AutoField):
        type_sql = "BIGINT GENERATED BY DEFAULT AS IDENTITY"
    elif isinstance(field, CharField):
        type_sql = f"VARCHAR({field.max_length})"
    elif isinstance(field, BooleanField):
        type_sql = "BOOLEAN"
    elif isinstance(field, DateTimeField):
        type_sql = "TIMESTAMPTZ"
    elif isinstance(field, IntegerField):
        type_sql = "INTEGER"
    else:
        raise TypeError(f"Unsupported migration field: {type(field).__name__}")
    constraints = " PRIMARY KEY" if field.primary_key else (
        "" if field.null else " NOT NULL"
    )
    if isinstance(field, ForeignKey):
        target_pk = field.to._meta.fields[field.to._meta.pk_name]
        constraints += (
            f" REFERENCES {_quote(field.to._meta.db_table)}"
            f" ({_quote(target_pk.column)}) ON DELETE {field.on_delete}"
        )
    return f"{_quote(field.column)} {type_sql}{constraints}"


def initial_migration(name: str, models: Iterable[type[Model]]) -> Migration:
    """Generate CREATE TABLE statements from the initial model definitions."""
    if not name or not name.replace("_", "").isalnum():
        raise ValueError("Migration name must contain letters, digits, or underscores")
    statements = []
    model_list = list(models)
    tables = set()
    for model in model_list:
        table = model._meta.db_table
        if table in tables:
            raise ValueError(f"Duplicate model table: {table}")
        tables.add(table)
    ordered: list[type[Model]] = []
    visiting: set[type[Model]] = set()
    visited: set[type[Model]] = set()

    def visit(model: type[Model]) -> None:
        if model in visited:
            return
        if model in visiting:
            raise ValueError("Circular foreign key dependencies are not supported")
        visiting.add(model)
        for field in model._meta.fields.values():
            if isinstance(field, ForeignKey) and field.to in model_list:
                visit(field.to)
        visiting.remove(model)
        visited.add(model)
        ordered.append(model)

    for model in model_list:
        visit(model)
    for model in ordered:
        table = model._meta.db_table
        columns = ", ".join(_column_sql(field)
                            for field in model._meta.fields.values())
        statements.append(f"CREATE TABLE {_quote(table)} ({columns})")
    if not statements:
        raise ValueError("An initial migration requires at least one model")
    return Migration(name, tuple(statements))


async def apply_migration(database: AsyncPostgres, migration: Migration) -> bool:
    """Apply once atomically; return False if the same version already ran."""
    async with database.transaction() as connection:
        await connection.execute(
            'CREATE TABLE IF NOT EXISTS "_asyncdjango_migrations" ('
            '"name" TEXT PRIMARY KEY, "checksum" CHAR(64) NOT NULL, '
            '"applied_at" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP)'
        )
        await connection.execute('LOCK TABLE "_asyncdjango_migrations" IN EXCLUSIVE MODE')
        rows = await connection.fetch(
            'SELECT "checksum" FROM "_asyncdjango_migrations" WHERE "name" = $1',
            migration.name,
        )
        if rows:
            if rows[0]["checksum"] != migration.checksum:
                raise RuntimeError(
                    f"Migration {migration.name!r} was already applied with different SQL"
                )
            return False
        for statement in migration.statements:
            await connection.execute(statement)
        await connection.execute(
            'INSERT INTO "_asyncdjango_migrations" ("name", "checksum") '
            'VALUES ($1, $2)', migration.name, migration.checksum,
        )
        return True
